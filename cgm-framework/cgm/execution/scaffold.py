"""Project/worker scaffolding + detached loop launch.

``do_new`` writes the on-disk layout a project needs; ``spawn_loop`` launches a
worker's outer loop detached in its own process group. Both are libraries the
``cgm`` CLI verbs (``cgm.orchestration``) call — kept here beside the loop +
layout so the file names, config template, and launch mechanism live in one place.

Notes:
  - the codex MCP wiring launches the installed package ``python -m cgm.gateway``
    (a pinned interface) rather than an absolute path to a server file;
  - the config template + defaults (verify URL, model) come from env at CALL time
    (with a built-in fallback default), not hard-wired at import time.
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
from pathlib import Path
from typing import Dict, List, Optional

from cgm import codex

from . import layout as L

# --------------------------------------------------------------------------- #
# atomic file helpers                                                         #
# --------------------------------------------------------------------------- #

def atomic_write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    os.replace(tmp, path)


def _toml_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def symlink(target: Path, link: Path) -> None:
    """Best-effort symlink; degrade gracefully where symlinks are unsupported
    (the codex config still points at the repo, so the worker isn't broken).

    Written RELATIVE to the link's own dir (both sides live inside the deployment
    tree), so the tree stays relocatable: move it, copy it to another host, or
    archive and hand it to a collaborator, and the links still resolve."""
    if link.is_symlink() or link.exists():
        return
    try:
        os.symlink(os.path.relpath(os.path.abspath(target),
                                   os.path.abspath(link.parent)), link)
    except OSError:
        pass


# --------------------------------------------------------------------------- #
# codex config template + task placeholder                                    #
# --------------------------------------------------------------------------- #

# The MCP server is the installed cgm gateway (role=worker) launched as a
# module — pinned interface (ARCHITECTURE.md §4): `python -m cgm.gateway` +
# CGM_ROLE. No absolute path to a server.py.
_CODEX_CONFIG = """\
# Auto-generated by `cgm new`. Re-run `cgm new` to refresh; do not hand-edit.

# Web search follows the deployment switch CGM_CODEX_WEB_SEARCH at `cgm new`
# time (and is re-asserted per round via `-c`); default off = offline-by-contract.
# Codex cross-session memories are always off (CODEX_HOME is shared with other
# runs and the operator's own sessions — every run must start cold).
[tools]
web_search = {web_search}

[features]
memories = false

[memories]
generate_memories = false
use_memories = false

[mcp_servers.cgm]
command = "python3"
args = ["-m", "cgm.gateway"]
# fact_submit blocks on the verify service (a cold-started codex that can reason
# for minutes on a hard proof); codex's default tool-call timeout is 120s, which
# would abort those legitimate long verifications. Match the verify HTTP timeout.
tool_timeout_sec = 3600

[mcp_servers.cgm.env]
CGM_PROJECT_DIR = {project_dir}
CGM_AUTHOR = {author}
CGM_ROLE = "worker"
CGM_VERIFY_URL = {verify_url}
CGM_DISABLE_EXTERNAL_SEARCH = {disable_external_search}
CGM_FACT_TEXT_MODE = {fact_text_mode}
CGM_DISABLE_EXPLORING_GRAPH = {disable_exploring_graph}
CGM_SELF_VERIFY_GATE = {self_verify_gate}
CGM_MEMORY_SCOPE = {memory_scope}
"""

_TASK_PLACEHOLDER = (
    "# Task\n\n(unassigned — the main agent writes your assignment here via "
    "`cgm assign`; you read this file at the start of every round)\n"
)


def _verify_url() -> str:
    # each fact_submit POSTs here; the verify service spawns a fresh codex to
    # verify. Standard local endpoint by default; override with CGM_VERIFY_URL.
    return os.environ.get("CGM_VERIFY_URL", "http://127.0.0.1:8091/verify")


def _default_model() -> str:
    return codex.model()


# --------------------------------------------------------------------------- #
# do_new — scaffold a project                                                 #
# --------------------------------------------------------------------------- #

def do_new(project: str, roles: str = "high:3,xhigh:4",
           model: Optional[str] = None, batch: Optional[str] = None) -> Dict:
    """Scaffold a project dir + one worker home per role. Refuses to clobber an
    existing project dir (no silent overwrite of a live fact graph). Returns
    ``{"project_dir", "workers"}``."""
    pdir = L.project_dir(project)
    if pdir.exists():
        raise SystemExit(f"project already exists: {pdir} (pick another name or remove it)")
    role_pairs = L.parse_roles(roles)
    model = model or _default_model()
    verify_url = _verify_url()

    L.workers_dir(project).mkdir(parents=True, exist_ok=True)
    (pdir / "global_memory").mkdir(exist_ok=True)
    (pdir / "fact_graph").mkdir(exist_ok=True)

    created: List[str] = []
    for worker, base in role_pairs:
        wl = L.WorkerLayout(L.worker_dir(project, worker))
        wl.local_memory.mkdir(parents=True, exist_ok=True)
        wl.logs.mkdir(exist_ok=True)

        # static contract + skills (symlinks stay in sync with the repo)
        symlink(L.worker_md(), wl.dir / "AGENTS.md")
        (wl.dir / ".agents").mkdir(exist_ok=True)
        symlink(L.worker_skills_dir(), wl.dir / ".agents" / "skills")

        # codex MCP wiring (role=worker)
        atomic_write(wl.codex_config, _CODEX_CONFIG.format(
            web_search="true" if codex.web_search_enabled() else "false",
            project_dir=_toml_str(str(pdir)),
            author=_toml_str(worker),
            verify_url=_toml_str(verify_url),
            disable_external_search=_toml_str(
                os.environ.get("CGM_DISABLE_EXTERNAL_SEARCH", "")),
            # ablation switches — empty (falsy) on a normal deployment
            fact_text_mode=_toml_str(
                os.environ.get("CGM_FACT_TEXT_MODE", "")),
            disable_exploring_graph=_toml_str(
                os.environ.get("CGM_DISABLE_EXPLORING_GRAPH", "")),
            self_verify_gate=_toml_str(
                os.environ.get("CGM_SELF_VERIFY_GATE", "")),
            # cross-project memory scope: worker codex env is an explicit
            # allowlist, so every gateway switch must be threaded through here
            memory_scope=_toml_str(
                os.environ.get("CGM_MEMORY_SCOPE", "off")),
        ))
        atomic_write(wl.task, _TASK_PLACEHOLDER)
        atomic_write(wl.role,
                     f"MODEL={model}\nREASONING_EFFORT={base}\nROLE={base}\nCGM_AUTHOR={worker}\n")
        atomic_write(wl.status,
                     json.dumps({"worker": worker, "state": "created", "round": 0}, indent=2))
        created.append(worker)

    meta = {"name": project, "model": model, "roles": roles, "workers": created}
    if batch:
        # experiment-protocol label: memory_recall can exclude same-batch
        # projects when the run is meant as independent trials
        meta["batch"] = batch
    atomic_write(pdir / "project.json", json.dumps(meta, ensure_ascii=False, indent=2))
    return {"project_dir": str(pdir), "workers": created}


# --------------------------------------------------------------------------- #
# spawn_loop — detached launch of one worker's outer loop                     #
# --------------------------------------------------------------------------- #

def spawn_loop(wdir: Path) -> int:
    """Launch ``python -m cgm.execution <wdir>`` detached in its own process
    group (``start_new_session=True``) so ``cgm stop --force`` can ``killpg``
    the loop *and* its in-flight codex child. Returns the child pid."""
    wl = L.WorkerLayout(wdir)
    wl.logs.mkdir(parents=True, exist_ok=True)
    logf = open(wl.logs / "loop.log", "a", encoding="utf-8")
    try:
        proc = subprocess.Popen(
            [sys.executable, "-m", "cgm.execution", str(wdir)],
            stdout=logf, stderr=subprocess.STDOUT, stdin=subprocess.DEVNULL,
            start_new_session=True,
        )
    finally:
        logf.close()
    return proc.pid
